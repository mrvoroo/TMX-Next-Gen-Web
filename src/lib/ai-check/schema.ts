/**
 * KI-Potenzial-Check – input and result shapes shared by the browser form
 * and the /api/ai-check route. Everything the visitor can choose is a fixed
 * enum; the only free text (live mode only) is length-capped.
 */

export const AI_INDUSTRIES = [
  'trades',
  'retail',
  'hospitality',
  'services',
  'health',
  'realestate',
  'manufacturing',
  'other',
] as const;
export const AI_SIZES = ['solo', 'small', 'medium', 'large'] as const;
export const AI_TASKS = [
  'emails',
  'quotes',
  'scheduling',
  'social',
  'texts',
  'reports',
  'documents',
  'support',
  'knowledge',
] as const;

export type AiIndustry = (typeof AI_INDUSTRIES)[number];
export type AiSize = (typeof AI_SIZES)[number];
export type AiTask = (typeof AI_TASKS)[number];
export type AiLocale = 'de' | 'en';
export type AiLevel = 'low' | 'medium' | 'high';
export type AiEffort = 'low' | 'medium' | 'high';

export const MAX_TASKS = 5;
export const MAX_NOTE = 300;
export const MAX_BODY_BYTES = 2048;

export interface AiCheckInput {
  locale: AiLocale;
  industry: AiIndustry;
  size: AiSize;
  tasks: AiTask[];
  /** Live mode only; never sent in demo mode. */
  note?: string;
  /** Live mode only: explicit consent to send the data to the AI provider. */
  consent?: boolean;
}

export interface AiCheckItem {
  task: AiTask;
  title: string;
  idea: string;
  effort: AiEffort;
  firstStep: string;
}

export interface AiCheckResult {
  /** "demo" = pre-written building blocks, "live" = generated by an AI model. */
  source: 'demo' | 'live';
  level: AiLevel;
  summary: string;
  items: AiCheckItem[];
  nextStep: string;
}

const isOneOf = <T extends readonly string[]>(list: T, v: unknown): v is T[number] =>
  typeof v === 'string' && (list as readonly string[]).includes(v);

/** Strips control characters and collapses whitespace. */
export function cleanText(v: string, max: number) {
  return v.replace(/[\u0000-\u001f\u007f]/g, ' ').replace(/\s+/g, ' ').trim().slice(0, max);
}

/** Returns a validated input or null. Unknown keys are dropped. */
export function parseAiCheckInput(raw: unknown): AiCheckInput | null {
  if (!raw || typeof raw !== 'object') return null;
  const r = raw as Record<string, unknown>;
  if (!isOneOf(['de', 'en'] as const, r.locale)) return null;
  if (!isOneOf(AI_INDUSTRIES, r.industry)) return null;
  if (!isOneOf(AI_SIZES, r.size)) return null;
  if (!Array.isArray(r.tasks) || r.tasks.length < 1 || r.tasks.length > MAX_TASKS) return null;
  const tasks = [...new Set(r.tasks)];
  if (!tasks.every((t) => isOneOf(AI_TASKS, t))) return null;
  if (r.note !== undefined && typeof r.note !== 'string') return null;
  if (typeof r.note === 'string' && r.note.length > MAX_NOTE) return null;
  return {
    locale: r.locale,
    industry: r.industry,
    size: r.size,
    tasks: tasks as AiTask[],
    note: typeof r.note === 'string' ? cleanText(r.note, MAX_NOTE) || undefined : undefined,
    consent: r.consent === true,
  };
}
